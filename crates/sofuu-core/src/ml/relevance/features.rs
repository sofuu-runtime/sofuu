// ml/relevance/features.rs — feature extraction for the relevance gate
// (PLAN-ML-GATES §6).
//
// One feature vector per CANDIDATE (a file, memory, or search result the
// retriever could pull into context) scored against the current task and
// the rest of the candidate set. The load-bearing signal is "does this
// deserve the tokens" — BM25 over the candidate set is the strong
// classical baseline (§6: the biggest accuracy win available given the
// bundled embedder is only hashed char-trigram TF-IDF); the semantic
// cosine, duplication, shape, and task×content interaction channels let
// the net correct the cases where lexical overlap alone is wrong
// (synonym matches, wrong-topic traps, task-dependent labels — §9).
// Deterministic: scalar f32, fixed order, injected context.

use std::collections::HashMap;
use std::sync::LazyLock;

use crate::ml::freshness::features::cosine;
use crate::rt::ai::sofuu_tfidf_embed;

pub const RELEVANCE_FEATURES: usize = 37;
const EMBED_DIM: usize = 768;

/// BM25 parameters — the standard retrieval defaults. Deterministic
/// constants, shared by training and serving (same code path).
const BM25_K1: f32 = 1.5;
const BM25_B: f32 = 0.75;

/// What kind of thing a candidate is. Drives the one-hot channel and the
/// brain strength/role features (memories only).
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum CandKind {
    File,
    Memory,
    Web,
    Other,
}

impl CandKind {
    fn one_hots(self) -> [f32; 4] {
        match self {
            CandKind::File => [1.0, 0.0, 0.0, 0.0],
            CandKind::Memory => [0.0, 1.0, 0.0, 0.0],
            CandKind::Web => [0.0, 0.0, 1.0, 0.0],
            CandKind::Other => [0.0, 0.0, 0.0, 1.0],
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct CandidateInput<'a> {
    pub text: &'a str,
    pub kind: CandKind,
    /// Brain memory strength in [0,1]; 0 for non-memories.
    pub strength: f32,
    /// Brain memory role id (0 = none / non-memory). Encoded as a scalar.
    pub role: u8,
    /// Source path when the candidate is a file ("" otherwise) — feeds the
    /// path/extension channels.
    pub path: &'a str,
}

/// Everything a candidate is scored against. `candidates` is the full menu
/// the retriever chose from (BM25's document collection); `kept` lists the
/// indices already accepted into context (near-duplicate detection);
/// `recent` is the recent visible history text (already-visible channel).
pub struct RelevanceContext<'a> {
    pub task: &'a str,
    pub recent: &'a str,
    pub candidates: &'a [CandidateInput<'a>],
    pub kept: &'a [usize],
}

