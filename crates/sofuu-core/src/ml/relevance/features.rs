    fn cand(text: &'static str, kind: CandKind) -> CandidateInput<'static> {
        CandidateInput { text, kind, strength: 0.0, role: 0, path: "" }
    }

    fn cand_file(text: &'static str, path: &'static str) -> CandidateInput<'static> {
        CandidateInput { text, kind: CandKind::File, strength: 0.0, role: 0, path }
    }

    #[test]
    fn vector_shape_and_determinism() {
        let cands = [
            cand_file("fn parse_config reads the toml file and returns the settings struct", "src/config.rs"),
            cand("the weather in oslo is unrelated to the task at hand", CandKind::Web),
            cand("remember to use the ripgrep binary for searches", CandKind::Memory),
        ];
        let ctx = RelevanceContext {
            task: "fix the parse_config function in the config module",
            recent: "",
            candidates: &cands,
            kept: &[],
        };
        let a = extract_all(&ctx);
        let b = extract_all(&ctx);
        assert_eq!(a.len(), 3);
        for (va, vb) in a.iter().zip(b.iter()) {
            assert_eq!(va.len(), RELEVANCE_FEATURES);
            for (x, y) in va.iter().zip(vb.iter()) {
                assert_eq!(x.to_bits(), y.to_bits(), "extraction must be deterministic");
            }
        }
    }

    /// Phase 1.3 (§5.3): empty/whitespace, NUL, Unicode, and path-like
    /// candidate texts over empty and hostile tasks — every feature must
    /// stay finite and in band, never panic.
    #[test]
    fn hostile_candidates_stay_finite_and_bounded() {
        let texts: Vec<String> = vec![
            String::new(),
            "  \t ".into(),
            "\u{0}\u{0}".into(),
            "配列😀\u{2028}".into(),
            "crate::path::to::mod".into(),
            "x".repeat(60_000),
            "deprecated deprecated deprecated".into(),
        ];
        let cands: Vec<CandidateInput> = texts
            .iter()
            .enumerate()
            .map(|(i, t)| CandidateInput {
                text: t,
                kind: [CandKind::File, CandKind::Memory, CandKind::Web, CandKind::Other][i % 4],
                strength: if i % 2 == 0 { f32::NAN } else { 2.5 },
                role: (i * 90) as u8,
                path: if i % 3 == 0 { "" } else { "src/deep/path/mod.rs" },
            })
            .collect();
        let ctx = RelevanceContext {
            task: "\u{0}latest 配列 version 😀",
            recent: "",
            candidates: &cands,
            kept: &[0, 3],
        };
        let v = extract_all(&ctx);
        assert_eq!(v.len(), cands.len());
        for (i, vec) in v.iter().enumerate() {
            for (j, x) in vec.iter().enumerate() {
                assert!(x.is_finite(), "cand {i} feature {j} NaN/Inf: {x}");
                assert!((-1.0..=2.0).contains(x), "cand {i} feature {j} out of band: {x}");
            }
        }
    }

    #[test]
    fn bm25_ranks_on_task_match() {
        let cands = [
            cand("database migration schema tables columns indexes migration", CandKind::File),
            cand("a recipe for sourdough bread with a long fermentation", CandKind::Web),
        ];
        let ctx = RelevanceContext {
            task: "finish the database migration",
            recent: "",
            candidates: &cands,
            kept: &[],
        };
        let v = extract_all(&ctx);
        // The on-task candidate has the better (lower) BM25 rank and a
        // higher normalized BM25 score.
        assert!(v[0][1] > v[1][1], "on-task BM25 score must be higher");
        assert!(v[0][2] < v[1][2], "on-task BM25 rank must be better (lower)");
    }

    #[test]
    fn near_duplicate_of_kept_is_flagged() {
        let cands = [
            cand("the session token expires after twenty minutes of inactivity", CandKind::File),
            cand("the session token expires after twenty minutes of inactivity", CandKind::File),
            cand("an entirely different note about the cache eviction policy", CandKind::File),
        ];
        let ctx = RelevanceContext {
            task: "debug the auth session expiry",
            recent: "",
            candidates: &cands,
            kept: &[0], // candidate 0 already accepted
        };
        let v = extract_all(&ctx);
        assert!(v[1][16] > 0.9, "verbatim repeat of a kept candidate must read as dup");
        assert_eq!(v[1][18], 1.0, "near-dup flag must fire");
        assert!(v[2][16] < 0.6, "unrelated candidate must not");
    }

    #[test]
    fn definition_site_fires_for_named_symbol() {
        let cands = [
            cand("fn evict_expired walks the lru cache and drops stale entries", CandKind::File),
            cand("evict_expired is mentioned in passing in an unrelated changelog", CandKind::File),
        ];
        let ctx = RelevanceContext {
            task: "fix the evict_expired function in the cache",
            recent: "",
            candidates: &cands,
            kept: &[],
        };
        let v = extract_all(&ctx);
        assert_eq!(v[0][32], 1.0, "definition site must fire");
        assert_eq!(v[1][32], 0.0, "mere mention must not");
    }

    #[test]
    fn task_dependent_label_channels() {
        // A changelog candidate: version-channel fires only when the TASK
        // is about versions.
        let changelog = cand("changelog version 2.0 breaking change deprecated the old api", CandKind::File);
        let version_task = RelevanceContext {
            task: "what changed in the latest version upgrade",
            recent: "",
            candidates: std::slice::from_ref(&changelog),
            kept: &[],
        };
        let other_task = RelevanceContext {
            task: "fix the null pointer in the parser",
            recent: "",
            candidates: std::slice::from_ref(&changelog),
            kept: &[],
        };
        let vv = extract_all(&version_task);
        let vo = extract_all(&other_task);
        assert_eq!(vv[0][28], 1.0, "version-task × version-content must fire");
        assert_eq!(vo[0][28], 0.0, "non-version task must not fire the channel");
    }

    #[test]
    fn stem_match_fires_on_morphological_echo() {
        // The answer echoes the task's domain words in DIFFERENT word forms
        // (migrates↔migration): exact-word overlap stays partial, the stem
        // channel must still fire. Goal tasks carry generic verbs
        // (finish/work) that never echo, so the ceiling is the domain-word
        // fraction — here 2 of 4 distinctive tokens.
        let cands = [
            cand("the routine migrates the storage schema, rewriting each table and rebuilding the column indexes before the database is swapped live", CandKind::Other),
            cand("office logistics memo about desks, badges, and parking slots in the annex building", CandKind::Other),
        ];
        let ctx = RelevanceContext {
            task: "finish the database migration work",
            recent: "",
            candidates: &cands,
            kept: &[],
        };
        let v = extract_all(&ctx);
        assert!(v[0][36] >= 0.5, "morphological echo must fire the stem channel");
        assert!(v[1][36] < 0.3, "unrelated content must not");
    }
