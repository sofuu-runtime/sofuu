// rt/digest.rs — MD5 / SHA-1 / SHA-256 / SHA-512 and RFC 2104 HMAC.
//
// AUDIT-2026-11-08 JR-053: the Node crypto shim answered createHash("sha1")
// and createHash("md5") with SHA-256, and createHmac ignored its key
// entirely — a signature check written against node:crypto either failed or,
// worse, accepted a forged MAC. These are the real algorithms, in-tree, so
// the runtime keeps its no-OpenSSL posture and adds no dependency.
//
// Only the primitives live here; the JS surface is rt/crypto.rs
// (sofuu.crypto.digest / sofuu.crypto.hmac) and the node:crypto shim in
// src/js/compat.js picks the algorithm by name.

use crate::rt::wal::Sha256;

/// A hash the shim can select by name.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Alg {
    Md5,
    Sha1,
    Sha256,
    Sha512,
}

impl Alg {
    /// Parse a node:crypto / OpenSSL style name. Node accepts both the short
    /// (sha256) and the hyphenated (sha-256) spellings; so do we, plus the
    /// common sha2-256 alias.
    pub fn parse(name: &str) -> Option<Alg> {
        let n = name.trim().to_ascii_lowercase().replace('_', "-");
        match n.as_str() {
            "md5" => Some(Alg::Md5),
            "sha1" | "sha-1" => Some(Alg::Sha1),
            "sha256" | "sha-256" | "sha2-256" => Some(Alg::Sha256),
            "sha512" | "sha-512" | "sha2-512" => Some(Alg::Sha512),
            _ => None,
        }
    }

    pub fn name(self) -> &'static str {
        match self {
            Alg::Md5 => "md5",
            Alg::Sha1 => "sha1",
            Alg::Sha256 => "sha256",
            Alg::Sha512 => "sha512",
        }
    }
}

/// Digest of data under alg.
pub fn digest(alg: Alg, data: &[u8]) -> Vec<u8> {
    match alg {
        Alg::Md5 => md5(data).to_vec(),
        Alg::Sha1 => sha1(data).to_vec(),
        Alg::Sha256 => {
            let mut h = Sha256::new();
            h.update(data);
            h.finalize().to_vec()
        }
        Alg::Sha512 => sha512(data).to_vec(),
    }
}

/// RFC 2104 HMAC of data under key, using alg as the hash.
pub fn hmac(alg: Alg, key: &[u8], data: &[u8]) -> Vec<u8> {
    let block = match alg {
        Alg::Md5 | Alg::Sha1 | Alg::Sha256 => 64,
        Alg::Sha512 => 128,
    };
    /* RFC 2104: K is hashed when longer than the block size, then zero-padded
     * to it. The inner and outer pads are K xor ipad / K xor opad. */
    let mut k = if key.len() > block {
        digest(alg, key)
    } else {
        key.to_vec()
    };
    k.resize(block, 0);
    let mut inner = Vec::with_capacity(block + data.len());
    let mut outer = Vec::with_capacity(block + 64);
    for &b in k.iter() {
        inner.push(b ^ 0x36);
        outer.push(b ^ 0x5c);
    }
    inner.extend_from_slice(data);
    outer.extend_from_slice(&digest(alg, &inner));
    digest(alg, &outer)
}

pub fn hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        out.push_str(&format!("{b:02x}"));
    }
    out
}

pub fn unhex(s: &str) -> Option<Vec<u8>> {
    let s = s.trim();
    if s.len() % 2 != 0 {
        return None;
    }
    let mut out = Vec::with_capacity(s.len() / 2);
    let bytes = s.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let hi = (bytes[i] as char).to_digit(16)?;
        let lo = (bytes[i + 1] as char).to_digit(16)?;
        out.push((hi * 16 + lo) as u8);
        i += 2;
    }
    Some(out)
}

