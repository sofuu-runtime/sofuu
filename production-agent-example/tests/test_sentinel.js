import fs from 'fs';
import path from 'path';
import { astScanTool, SECURITY_RULES } from '../lib/tools/ast_scan.js';
import { reportGenTool, calculateRiskScore, renderMarkdownReport } from '../lib/tools/report_gen.js';
import { gitDiffTool } from '../lib/tools/git_diff.js';
import { defineSentinelAgent } from '../lib/sentinel.js';
import { defineSecuritySpecialist } from '../lib/specialists/security.js';
import { defineQualitySpecialist } from '../lib/specialists/quality.js';

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    passed++;
    console.log(`  \x1b[32mPASS\x1b[0m ${message}`);
  } else {
    failed++;
    console.error(`  \x1b[31mFAIL\x1b[0m ${message}`);
  }
}

async function runTests() {
  console.log('\n🧪 Testing Production Sentinel Agent Components\n');

  // Test 1: Agent Registry & Definition
  console.log('1. Testing Agent Registration & Sub-Agent Hierarchies');
  {
    const sentinel = defineSentinelAgent();
    assert(sentinel.name === 'code_sentinel', 'Supervisor agent name is code_sentinel');

    const list = sofuu.agent.list();
    const names = list.map((a) => a.name);
    assert(names.includes('code_sentinel'), 'code_sentinel registered in runtime');
    assert(names.includes('security_scanner'), 'security_scanner sub-agent registered');
    assert(names.includes('quality_expert'), 'quality_expert sub-agent registered');

    const sentinelDef = list.find((a) => a.name === 'code_sentinel');
    assert(sentinelDef.agents.includes('security_scanner'), 'Supervisor declares security_scanner sub-agent');
    assert(sentinelDef.agents.includes('quality_expert'), 'Supervisor declares quality_expert sub-agent');
  }

  // Test 2: AST Security Scanner Tool
  console.log('\n2. Testing AST Static Security Scanner Tool');
  {
    const fixtureDir = path.resolve(process.cwd(), 'production-agent-example/tests/fixtures');
    if (!fs.existsSync(fixtureDir)) fs.mkdirSync(fixtureDir, { recursive: true });

    const vulnerableCode = [
      '// Insecure test file',
      'const apiKey = "sk-live-abcdef123456789012345678";',
      'const userQuery = req.query.id;',
      'const res = eval("2 + " + userQuery);',
      'const sql = "SELECT * FROM users WHERE id = " + userQuery;',
      'const md5 = crypto.createHash("md5").update(password).digest("hex");',
    ].join('\n');

    const testFile = path.join(fixtureDir, 'vulnerable_sample.js');
    fs.writeFileSync(testFile, vulnerableCode, 'utf8');

    const resultRaw = await astScanTool.execute({
      targetPath: testFile,
      severityFloor: 'LOW',
    });
    const result = JSON.parse(resultRaw);

    assert(result.ok === true, 'ast_scan executed successfully');
    assert(result.totalFindings >= 4, `ast_scan detected vulnerabilities (found ${result.totalFindings})`);
    assert(result.severityCounts.critical >= 2, 'ast_scan flagged critical vulnerabilities');

    // Clean up test fixture
    try {
      fs.unlinkSync(testFile);
      fs.rmdirSync(fixtureDir);
    } catch (_) {}
  }

  // Test 3: Report Generator Tool & Risk Scoring
  console.log('\n3. Testing Audit Report Generator & Risk Score Math');
  {
    const counts = { critical: 1, high: 2, medium: 3, low: 4 };
    const score = calculateRiskScore(counts);
    // 100 - (1*25 + 2*10 + 3*4 + 4*1) = 100 - (25 + 20 + 12 + 4) = 100 - 61 = 39
    assert(score === 39, `Risk score calculation is exact (expected 39, got ${score})`);

    const cleanCounts = { critical: 0, high: 0, medium: 0, low: 0 };
    assert(calculateRiskScore(cleanCounts) === 100, 'Clean codebase scores 100/100');

    const outReport = path.resolve(process.cwd(), 'production-agent-example/tests/sample-report.md');
    const genResRaw = await reportGenTool.execute({
      title: 'Automated Test Verification Run',
      executiveSummary: 'This is a test audit report generated by automated testing.',
      severityCounts: counts,
      findings: [
        {
          ruleId: 'SEC-001',
          name: 'Hardcoded Token',
          severity: 'CRITICAL',
          category: 'Secret Leak',
          file: 'src/app.js',
          line: 42,
          snippet: 'const token = "sk-live-1234567890";',
          remediation: 'Use environment variables.',
        },
      ],
      recommendations: [{ title: 'Rotate Secrets', action: 'Immediately revoke leaked keys.' }],
      outputPath: outReport,
    });
    const genRes = JSON.parse(genResRaw);

    assert(genRes.ok === true, 'report_gen executed and generated file');
    assert(fs.existsSync(outReport), 'Report file exists on disk');

    const content = fs.readFileSync(outReport, 'utf8');
    assert(content.includes('Security Posture Score'), 'Report contains security posture score');
    assert(content.includes('Hardcoded Token'), 'Report lists discovered vulnerability');

    // Clean up sample report
    try {
      fs.unlinkSync(outReport);
    } catch (_) {}
  }

  // Test 4: Git Diff Tool
  console.log('\n4. Testing Git Diff Tool Execution');
  {
    const diffRaw = await gitDiffTool.execute({ fileLimit: 10 });
    const diffRes = JSON.parse(diffRaw);
    assert(diffRes.ok === true, 'git_diff executed without error');
    assert(typeof diffRes.totalChangedFiles === 'number', 'git_diff returned totalChangedFiles count');
  }

  console.log('\n─────────────────────────────────────────────');
  console.log(`Test Results: ${passed} passed, ${failed} failed`);
  console.log('─────────────────────────────────────────────\n');

  if (failed > 0) {
    process.exit(1);
  }
}

runTests();
