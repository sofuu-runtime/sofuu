package com.sofuu.ui.soapbubble

/**
 * Material settings for the soap-bubble surface, ported one field per
 * `SoapBubbleTuning` field in the React component. Defaults are the component's
 * published defaults; [lightPreset] is the approved catalog default.
 */
data class SoapBubbleSettings(
    val radius: Float = 9999f,
    val bevel: Float = 14f,
    val thickness: Float = 480f,
    val iridescence: Float = 2f,
    val drainage: Float = 0.35f,
    val swirl: Float = 0.5f,
    val filmScale: Float = 4.85f,
    val oilOpacity: Float = 1f,
    val oilCoverage: Float = 1f,
    val oilEdge: Float = 18f,
    val oilEdgeFade: Float = 1f,
    val clearCenter: Float = 0.73f,
    val tint: String = "#ffffff00",
    val soapColor: String = "auto",
    val soapPalette: String = "natural",
    val soapPaletteRed: String = "#ff6685",
    val soapPaletteGold: String = "#f6d365",
    val soapPaletteGreen: String = "#83e8a9",
    val soapPaletteCyan: String = "#60dce9",
    val soapPaletteBlue: String = "#7799ff",
    val soapPaletteViolet: String = "#c084fc",
    val soapShadeColor: String = "auto",
    val soapHighlightColor: String = "auto",
    val reflectivity: Float = 1.3f,
    val mirage: Float = 0.7f,
    val seeThrough: Float = 0.3f,
    val seeThroughBend: Float = 0.3f,
    val opacity: Float = -1f,
    val floorLight: Float = 1f,
    val windowLight: Boolean = false,
    val windowStyle: String = "edge",
    val windowLength: Float = 1.3f,
    val windowMargin: Float = 0.85f,
    val windowBend: Float = 0.75f,
    val windowSize: Float = 0.75f,
    val windowWidth: Float = 0.8f,
    val windowGradient: Float = 0.96f,
    val topFade: Float = 0.4f,
    val topTail: Float = 1f,
    val topLength: Float = 1f,
    val windowHead: Float = 0.7f,
    val windowTail: Float = 0.6f,
    val glintShape: String = "auto",
    val glintSize: Float = 1.65f,
    val glintIntensity: Float = 0f,
    val glintDistance: Float = -0.45f,
    val glintHeight: Float = 0.65f,
    val windowIntensity: Float = 0.85f,
    val windowTwin: Boolean = false,
    val windowTwinShape: String = "mirror",
    val keyLight: Boolean = true,
    val bottomShade: Boolean = false,
    val bottomShadeColor: String = "#ffffff",
    val reach: Float = 2f,
    val refraction: Float = 0.15f,
    val glass: Float = 0.95f,
    val dispersion: Float = 1f,
    val environment: String = "auto",
    val tilt: Float = 1f,
    val wobble: Float = 0.4f,
    val speed: Float = 1f,
    val paused: Boolean = false,
    val seed: Float = 7f,
    val maxDpr: Float = 2f,
    /** Dark page: the film refracts a dark wash and skips the light-theme
     *  oil coating. Sofuu's dark theme sets this; the reference default is
     *  light (its app was light-only). */
    val dark: Boolean = false,
) {
    fun normalized(): SoapBubbleSettings = copy(
        radius = radius.clamp(0f, 9999f, 9999f),
        bevel = bevel.clamp(2f, 200f, 14f),
        thickness = thickness.clamp(0f, 2400f, 480f),
        iridescence = iridescence.clamp(0f, 3f, 2f),
        drainage = drainage.clamp(0f, 1f, 0.35f),
        swirl = swirl.clamp(0f, 1f, 0.5f),
        filmScale = filmScale.clamp(0.2f, 6f, 4.85f),
        oilOpacity = oilOpacity.clamp(0f, 1f, 1f),
        oilCoverage = oilCoverage.clamp(0f, 1f, 1f),
        oilEdge = oilEdge.clamp(0f, 400f, 18f),
        oilEdgeFade = oilEdgeFade.clamp(0f, 3f, 1f),
        clearCenter = clearCenter.clamp(0f, 1f, 0.73f),
        reflectivity = reflectivity.clamp(0f, 6f, 1.3f),
        mirage = mirage.clamp(0f, 3f, 0.7f),
        seeThrough = seeThrough.clamp(0f, 1f, 0.3f),
        seeThroughBend = seeThroughBend.clamp(0f, 2f, 0.3f),
        opacity = opacity.clamp(-1f, 1f, -1f),
        floorLight = floorLight.clamp(0f, 1f, 1f),
        windowLength = windowLength.clamp(0.3f, 2f, 1.3f),
        windowMargin = windowMargin.clamp(0.4f, 2.2f, 0.85f),
        windowBend = windowBend.clamp(0f, 1f, 0.75f),
        windowSize = windowSize.clamp(0.4f, 2f, 0.75f),
        windowWidth = windowWidth.clamp(0.3f, 2.5f, 0.8f),
        windowGradient = windowGradient.clamp(0f, 1f, 0.96f),
        topFade = topFade.clamp(0f, 1f, 0.4f),
        topTail = topTail.clamp(0.05f, 2f, 1f),
        topLength = topLength.clamp(0.2f, 2.5f, 1f),
        windowHead = windowHead.clamp(0.3f, 2f, 0.7f),
        windowTail = windowTail.clamp(0.05f, 2.5f, 0.6f),
        glintSize = glintSize.clamp(0f, 3f, 1.65f),
        glintIntensity = glintIntensity.clamp(0f, 2f, 0f),
        glintDistance = glintDistance.clamp(-1f, 2f, -0.45f),
        glintHeight = glintHeight.clamp(-1.5f, 1.5f, 0.65f),
        windowIntensity = windowIntensity.clamp(0f, 2f, 0.85f),
        reach = reach.clamp(0.5f, 8f, 2f),
        refraction = refraction.clamp(0f, 1f, 0.15f),
        glass = glass.clamp(0f, 1f, 0.95f),
        dispersion = dispersion.clamp(0f, 3f, 1f),
        tilt = tilt.clamp(0f, 2f, 1f),
        wobble = wobble.clamp(0f, 3f, 0.4f),
        speed = speed.clamp(0f, 4f, 1f),
        seed = seed.clamp(0f, 9999f, 7f),
        maxDpr = maxDpr.clamp(0.5f, 3f, 2f),
    )

    companion object {
        /**
         * Light glass on light pages: the catalog default. The oil controls
         * are exactly the approved light values.
         */
        val lightPreset = SoapBubbleSettings(
            glass = 0.95f,
            iridescence = 0.5f,
            filmScale = 4.85f,
            oilOpacity = 1f,
            oilCoverage = 0.73f,
            oilEdge = 18f,
            oilEdgeFade = 2.33f,
            clearCenter = 0.57f,
            thickness = 480f,
            drainage = 0.35f,
            swirl = 0.5f,
            reflectivity = 1.3f,
            refraction = 0.15f,
            dispersion = 1f,
            bevel = 14f,
            environment = "soft",
        )

        private fun Float.clamp(min: Float, max: Float, fallback: Float): Float =
            if (isFinite()) coerceIn(min, max) else fallback
    }
}
